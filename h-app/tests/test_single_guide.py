"""Issue #31: one per-agent guide file (AGENTS.md), CLAUDE.md only when we must.

The single-guide path is taken only when `claude_reads_agents_md` positively
establishes claude's AGENTS.md fallback; everything uncertain keeps the
dual-write. A CLAUDE.md is removed only if provably generated by us.
"""
import json
import subprocess
from pathlib import Path

import pytest

import modules.tmux.ops as ops
from modules.tmux.reconciler import TmuxReconciler

REAL_CLAUDE_VERSION = ops._claude_version  # conftest replaces the module attribute per test
TESTED = ops.CLAUDE_AGENTS_MD_FLOOR


@pytest.fixture
def env(tmp_path, monkeypatch):
    home = tmp_path / "home"
    home.mkdir()
    managed = tmp_path / "etc-claude-code"
    managed.mkdir()
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.delenv("OPERATOR_ENTRANCE", raising=False)
    monkeypatch.setattr(ops, "MANAGED_SETTINGS_DIR", str(managed))
    monkeypatch.setattr(ops, "_claude_version", lambda: TESTED)
    logged = []
    monkeypatch.setattr(ops, "log_record", lambda module, event, **kw: logged.append((event, kw.get("reason", ""))))
    cwd = tmp_path / "work" / "worker"
    return type("Env", (), {"home": home, "managed": managed, "cwd": cwd, "logged": logged})


def _write(env, **kw):
    ops.write_agent_guide(str(env.cwd), "worker", **kw)
    agents = env.cwd / "AGENTS.md"
    claude = env.cwd / "CLAUDE.md"
    return agents, claude


def test_floor_is_the_tested_version():
    assert TESTED == (2, 1, 302)


def test_single_guide_when_fallback_is_established(env):
    agents, claude = _write(env)
    assert agents.read_text(encoding="utf-8").startswith("You are **worker**")
    assert not claude.exists()


def test_newer_claude_is_fine(env, monkeypatch):
    monkeypatch.setattr(ops, "_claude_version", lambda: (2, 2, 0))
    _, claude = _write(env)
    assert not claude.exists()


@pytest.mark.parametrize("version", [None, (2, 1, 301), (1, 9, 9)])
def test_unknown_or_old_claude_keeps_dual_write(env, monkeypatch, version):
    monkeypatch.setattr(ops, "_claude_version", lambda: version)
    agents, claude = _write(env)
    assert claude.read_text(encoding="utf-8") == agents.read_text(encoding="utf-8")


OVERRIDES = [
    {"instructionFiles": "claude-md"},
    {"instructionFiles": "managed-only"},
    {"instructionFiles": ["claude-md"]},
    {"instructionFiles": None},
    {"projectInstructions": "claude"},
    {"projectInstructions": "none"},
    {"projectInstructions": 3},
]
SOURCES = {
    "user": lambda e: e.home / ".claude" / "settings.json",
    "project": lambda e: e.cwd / ".claude" / "settings.json",
    "local": lambda e: e.cwd / ".claude" / "settings.local.json",
    "managed": lambda e: e.managed / "managed-settings.json",
    "managed.d": lambda e: e.managed / "managed-settings.d" / "10-org.json",
}


def _put(path: Path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(data if isinstance(data, str) else json.dumps(data), encoding="utf-8")


@pytest.mark.parametrize("source", sorted(SOURCES))
@pytest.mark.parametrize("override", OVERRIDES, ids=lambda o: json.dumps(o))
def test_any_override_in_any_settings_source_keeps_dual_write(env, source, override):
    _put(SOURCES[source](env), override)
    agents, claude = _write(env)
    assert claude.read_text(encoding="utf-8") == agents.read_text(encoding="utf-8")


@pytest.mark.parametrize("source", sorted(SOURCES))
@pytest.mark.parametrize("bad", ["{not json", "[1, 2]", '"text"'])
def test_unreadable_or_malformed_settings_keeps_dual_write(env, source, bad):
    _put(SOURCES[source](env), bad)
    _, claude = _write(env)
    assert claude.exists()


@pytest.mark.parametrize("ok", [
    {"instructionFiles": "claude-md-or-agents-md"},
    {"instructionFiles": "claude-md-and-agents-md"},
    {"projectInstructions": "agents-fallback"},
    {"projectInstructions": "both"},
    {"theme": "dark"},
])
def test_non_blocking_settings_still_allow_single_guide(env, ok):
    _put(SOURCES["user"](env), ok)
    _put(SOURCES["project"](env), {"theme": "dark"})
    _, claude = _write(env)
    assert not claude.exists()


def test_profile_reads_its_own_config_dir_only(env):
    _put(env.home / ".claude-work" / "settings.json", {"instructionFiles": "claude-md"})
    _, claude = _write(env, profile="work")
    assert claude.exists()
    claude.unlink()
    # The default account's override is not what a `work` agent reads...
    _put(env.home / ".claude-work" / "settings.json", {})
    _put(env.home / ".claude" / "settings.json", {"instructionFiles": "claude-md"})
    _, claude = _write(env, profile="work")
    assert not claude.exists()
    # ...but it is what an unprofiled agent reads.
    _, claude = _write(env)
    assert claude.exists()


def test_ancestor_claude_md_keeps_dual_write(env):
    (env.cwd.parent).mkdir(parents=True)
    (env.cwd.parent / "CLAUDE.md").write_text("# a parent's own\n", encoding="utf-8")
    ok, why = ops.claude_reads_agents_md(str(env.cwd))
    assert not ok and "ancestor" in why
    _, claude = _write(env)
    assert claude.exists()


def test_reversal_restores_claude_md(env):
    _, claude = _write(env)
    assert not claude.exists()
    _put(SOURCES["project"](env), {"instructionFiles": "claude-md"})
    agents, claude = _write(env)
    assert claude.read_text(encoding="utf-8") == agents.read_text(encoding="utf-8")


# --- never delete a CLAUDE.md we did not generate -------------------------------

def test_stale_claude_md_identical_to_the_previous_agents_md_is_removed(env):
    env.cwd.mkdir(parents=True)
    old = "OLD TEMPLATE guide text\n"  # an older build's guide, differs from today's
    (env.cwd / "AGENTS.md").write_text(old, encoding="utf-8")
    (env.cwd / "CLAUDE.md").write_text(old, encoding="utf-8")
    agents, claude = _write(env)
    assert not claude.exists()
    assert agents.read_text(encoding="utf-8") != old
    assert any(e == "guide_claude_md_removed" for e, _ in env.logged)


def test_stale_claude_md_identical_to_the_new_guide_is_removed(env):
    agents, _ = _write(env)
    (env.cwd / "CLAUDE.md").write_bytes(agents.read_bytes())
    (env.cwd / "AGENTS.md").write_text("hand-edited AGENTS.md\n", encoding="utf-8")
    _, claude = _write(env)
    assert not claude.exists()


def test_foreign_claude_md_is_kept_and_logged(env):
    env.cwd.mkdir(parents=True)
    mine = "# my own notes for this agent\n"
    (env.cwd / "CLAUDE.md").write_text(mine, encoding="utf-8")
    agents, claude = _write(env)
    assert claude.read_text(encoding="utf-8") == mine
    assert agents.exists()
    errors = [r for e, r in env.logged if e == "error" and "left in place" in r]
    assert errors and str(claude) in errors[0]


def test_symlinked_claude_md_is_never_removed(env):
    env.cwd.mkdir(parents=True)
    target = env.cwd / "elsewhere.md"
    agents, _ = _write(env)
    target.write_bytes(agents.read_bytes())
    (env.cwd / "CLAUDE.md").symlink_to(target)
    _write(env)
    assert (env.cwd / "CLAUDE.md").is_symlink()
    assert target.exists()


# --- migration of already-live agents -----------------------------------------------

def _live(env, claude_text):
    env.cwd.mkdir(parents=True)
    (env.cwd / "AGENTS.md").write_text("guide\n", encoding="utf-8")
    if claude_text is not None:
        (env.cwd / "CLAUDE.md").write_text(claude_text, encoding="utf-8")


def test_migrate_removes_an_identical_duplicate_without_rewriting_agents_md(env):
    _live(env, "guide\n")
    assert ops.migrate_agent_guide(str(env.cwd)) == "removed"
    assert not (env.cwd / "CLAUDE.md").exists()
    assert (env.cwd / "AGENTS.md").read_text(encoding="utf-8") == "guide\n"


def test_migrate_leaves_a_different_claude_md_and_logs(env):
    _live(env, "something else\n")
    assert ops.migrate_agent_guide(str(env.cwd)).startswith("kept")
    assert (env.cwd / "CLAUDE.md").read_text(encoding="utf-8") == "something else\n"
    assert any(e == "error" and "left in place" in r for e, r in env.logged)


def test_migrate_needs_the_agents_md_beside_it(env):
    env.cwd.mkdir(parents=True)
    (env.cwd / "CLAUDE.md").write_text("guide\n", encoding="utf-8")
    assert ops.migrate_agent_guide(str(env.cwd)) == "kept: no AGENTS.md beside it"
    assert (env.cwd / "CLAUDE.md").exists()


def test_migrate_does_nothing_when_fallback_cannot_be_relied_on(env, monkeypatch):
    _live(env, "guide\n")
    monkeypatch.setattr(ops, "_claude_version", lambda: None)
    assert ops.migrate_agent_guide(str(env.cwd)).startswith("kept: claude --version")
    assert (env.cwd / "CLAUDE.md").exists()
    _put(SOURCES["project"](env), {"instructionFiles": "claude-md"})
    monkeypatch.setattr(ops, "_claude_version", lambda: TESTED)
    assert ops.migrate_agent_guide(str(env.cwd)).startswith("kept")
    assert (env.cwd / "CLAUDE.md").exists()


def test_migrate_reports_absent(env):
    _live(env, None)
    assert ops.migrate_agent_guide(str(env.cwd)) == "absent"


class _R:  # minimal redis stand-in: no profile key
    def get(self, key):
        return None


def test_reconciler_sweeps_each_agent_once_per_process(env, monkeypatch):
    monkeypatch.setenv("H_MESH_WORKDIR", str(env.cwd.parent))
    rec = TmuxReconciler(pod="p", tenant="t", redis_url="redis://unused")
    _live(env, "guide\n")
    rec._migrate_guides(_R(), {"worker"})
    assert not (env.cwd / "CLAUDE.md").exists()
    # Re-created identical copy is NOT touched again by the same process.
    (env.cwd / "CLAUDE.md").write_text("guide\n", encoding="utf-8")
    rec._migrate_guides(_R(), {"worker"})
    assert (env.cwd / "CLAUDE.md").exists()


def test_reconciler_sweep_never_raises(env, monkeypatch):
    monkeypatch.setenv("H_MESH_WORKDIR", str(env.cwd.parent))
    rec = TmuxReconciler(pod="p", tenant="t", redis_url="redis://unused")

    def boom(*a, **k):
        raise RuntimeError("boom")

    monkeypatch.setattr("modules.tmux.reconciler.tmux_ops.migrate_agent_guide", boom)
    rec._migrate_guides(_R(), {"worker"})


# --- claude --version parsing -----------------------------------------------------------

@pytest.mark.parametrize("stdout,code,expected", [
    ("2.1.302 (Claude Code)\n", 0, (2, 1, 302)),
    ("2.1.316 (Claude Code)\n", 0, (2, 1, 316)),
    ("Claude Code v2.2.0\n", 0, (2, 2, 0)),
    ("no version here\n", 0, None),
    ("2.1.316\n", 1, None),
])
def test_claude_version_parsing(monkeypatch, stdout, code, expected):
    REAL_CLAUDE_VERSION.cache_clear()
    monkeypatch.setattr(
        ops.subprocess, "run",
        lambda *a, **k: subprocess.CompletedProcess(a, code, stdout=stdout, stderr=""),
    )
    try:
        assert REAL_CLAUDE_VERSION() == expected
    finally:
        REAL_CLAUDE_VERSION.cache_clear()


@pytest.mark.parametrize("exc", [FileNotFoundError(), subprocess.TimeoutExpired("claude", 5), OSError()])
def test_claude_version_unavailable_is_none(monkeypatch, exc):
    REAL_CLAUDE_VERSION.cache_clear()

    def raiser(*a, **k):
        raise exc

    monkeypatch.setattr(ops.subprocess, "run", raiser)
    try:
        assert REAL_CLAUDE_VERSION() is None
    finally:
        REAL_CLAUDE_VERSION.cache_clear()


def test_claude_version_is_not_cached_for_the_process_lifetime(monkeypatch):
    """A fresh container writes the guide on the installer's claude, which then self-updates."""
    REAL_CLAUDE_VERSION.cache_clear()
    clock = [1000.0]
    out = ["2.1.302 (Claude Code)\n"]
    monkeypatch.setattr(ops.time, "monotonic", lambda: clock[0])
    monkeypatch.setattr(
        ops.subprocess, "run",
        lambda *a, **k: subprocess.CompletedProcess(a, 0, stdout=out[0], stderr=""),
    )
    try:
        assert REAL_CLAUDE_VERSION() == (2, 1, 302)
        out[0] = "2.1.316 (Claude Code)\n"
        assert REAL_CLAUDE_VERSION() == (2, 1, 302)  # inside the TTL
        clock[0] += ops._VERSION_TTL_SECONDS + 1
        assert REAL_CLAUDE_VERSION() == (2, 1, 316)  # picked up after the TTL
    finally:
        REAL_CLAUDE_VERSION.cache_clear()


def test_reconciler_retries_a_sweep_blocked_by_claude_version(env, monkeypatch):
    monkeypatch.setenv("H_MESH_WORKDIR", str(env.cwd.parent))
    rec = TmuxReconciler(pod="p", tenant="t", redis_url="redis://unused")
    _live(env, "guide\n")
    monkeypatch.setattr(ops, "_claude_version", lambda: None)
    rec._migrate_guides(_R(), {"worker"})
    assert (env.cwd / "CLAUDE.md").exists()
    monkeypatch.setattr(ops, "_claude_version", lambda: TESTED)
    rec._migrate_guides(_R(), {"worker"})
    assert not (env.cwd / "CLAUDE.md").exists()
